import Link from "next/link";
import { Award, GraduationCap } from "lucide-react";
import {
  StudentAchievementEmptyState,
  StudentPageHeader,
} from "@/components/student/student-components";
import CertificateDownloadButton from "@/components/student/certificate-download-button";
import { getStudentAchievementsPageData } from "@/lib/student/data";
import { formatCertificateIssueDate } from "@/lib/certificates/date";
import { formatDate } from "@/lib/student/time";

export const metadata = {
  title: "Achievements",
  robots: { index: false, follow: false },
};

export default async function StudentAchievementsPage() {
  const data = await getStudentAchievementsPageData();
  const hasAchievements = data.certificates.length || data.completedCourses.length;

  return (
    <div className="student-page">
      <StudentPageHeader
        eyebrow="Earned through learning"
        title="Achievements"
        description="Only issued certificates and completed enrollments are shown. No rewards are generated by visiting this page."
      />

      {!hasAchievements ? (
        <section className="student-panel">
          <StudentAchievementEmptyState />
        </section>
      ) : (
        <>
          <section className="student-panel">
            <header className="student-panel-heading">
              <div>
                <p className="student-eyebrow">Verified records</p>
                <h2>Earned certificates</h2>
              </div>
              <Award size={20} aria-hidden="true" />
            </header>
            {data.certificates.length ? (
              <div className="student-achievement-list">
                {data.certificates.map((certificate) => (
                  <article className="student-achievement-card" key={certificate.id}>
                    <span className="student-achievement-icon"><Award size={21} aria-hidden="true" /></span>
                    <div className="student-achievement-copy">
                      <p className="student-eyebrow">Issued certificate</p>
                      <h3>{certificate.course?.title || "Completed course"}</h3>
                      <p>
                        Certificate number <strong>{certificate.certificate_number}</strong>
                      </p>
                      <time dateTime={certificate.issued_at}>
                        Issued {formatCertificateIssueDate(certificate.issued_at)}
                      </time>
                    </div>
                    {certificate.downloadUrl ? (
                      <CertificateDownloadButton downloadUrl={certificate.downloadUrl} />
                    ) : null}
                    <Link
                      className="student-inline-link"
                      href={`/verify/${certificate.verification_code}`}
                    >
                      Verify certificate
                    </Link>
                  </article>
                ))}
              </div>
            ) : (
              <p className="student-section-empty">
                No certificates have been issued to your account yet.
              </p>
            )}
          </section>

          <section className="student-panel">
            <header className="student-panel-heading">
              <div>
                <p className="student-eyebrow">Course completion history</p>
                <h2>Completed courses</h2>
              </div>
              <GraduationCap size={20} aria-hidden="true" />
            </header>
            {data.completedCourses.length ? (
              <ul className="student-completion-list">
                {data.completedCourses.map((enrollment) => (
                  <li key={enrollment.id}>
                    <span className="student-completion-icon">
                      <GraduationCap size={18} aria-hidden="true" />
                    </span>
                    <div>
                      <Link href={`/courses/${enrollment.course.slug}`}>
                        {enrollment.course.title}
                      </Link>
                      <time dateTime={enrollment.updated_at}>
                        Completed {formatDate(enrollment.updated_at)}
                      </time>
                    </div>
                    {enrollment.revokedCertificate && (
                      <p className="student-section-empty" role="status">
                        Certificate {enrollment.revokedCertificate.certificate_number}
                        {" "}was revoked and is no longer valid.{" "}
                        <Link
                          href={`/verify/${enrollment.revokedCertificate.verification_code}`}
                        >
                          Check its current status
                        </Link>
                        .
                      </p>
                    )}
                    {!enrollment.certificateIssued &&
                      !enrollment.revokedCertificate &&
                      enrollment.eligibility?.eligible && (
                        <p className="student-section-empty" role="status">
                          Certificate issuance is automatic. If it does not appear
                          after refreshing, contact support.
                        </p>
                      )}
                    {!enrollment.certificateIssued &&
                      !enrollment.revokedCertificate &&
                      !enrollment.eligibility?.eligible && (
                        <p className="student-section-empty">
                          Certificate requirements are not yet satisfied:
                          lesson completion{" "}
                          {enrollment.eligibility?.lesson_completion_percent ?? 0}%
                          /{" "}
                          {enrollment.eligibility?.required_lesson_completion_percent ?? 100}%
                          , required assessments{" "}
                          {enrollment.eligibility?.required_assessments_passed ?? 0}
                          /
                          {enrollment.eligibility?.required_assessments_total ?? 0}
                          {enrollment.eligibility?.require_final_exam &&
                            `, final examination ${enrollment.eligibility.final_exam_passed ? "passed" : "not passed"}`}
                          .
                        </p>
                      )}
                  </li>
                ))}
              </ul>
            ) : (
              <p className="student-section-empty">
                Completed courses will appear here after all published lessons are recorded as complete.
              </p>
            )}
          </section>
        </>
      )}
    </div>
  );
}
